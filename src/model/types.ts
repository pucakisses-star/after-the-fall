/**
 * A read-only real-world dataset shown underneath the political map. These are
 * *not* part of the editable document — they are a tracing/reference aid, and
 * `convertBasemapToTerritories()` is what turns a selection of them into real
 * editable `Territory` records (§3: "the user should not be forced to trace the
 * entire coastline of North America manually").
 */
export interface BasemapSource {
  id: string;
  name: string;
  /** URL under /data, or an object URL for user imports. */
  url: string;
  format: 'topojson' | 'geojson';
  /** TopoJSON object key to extract. */
  objectName?: string;
  role: 'land' | 'countries' | 'states' | 'counties' | 'lakes' | 'rivers' | 'roads' | 'places' | 'custom';
}

export interface BasemapLayerState {
  sourceId: string;
  visible: boolean;
  opacity: number;
}

