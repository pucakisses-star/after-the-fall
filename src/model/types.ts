export interface ProjectMeta {
  title: string;
  subtitle: string;
  author: string;
  /** Free text — "in the year 1453". Not parsed. */
  dateLine: string;
  notes: string;
  createdAt: string; // ISO
  modifiedAt: string; // ISO
}

export interface SavedView {
  center: [number, number]; // WGS84
  /** OpenLayers zoom level. */
  zoom: number;
  rotation: number;
}

export interface MapProject {
  /** Bumped whenever the on-disk shape changes; `migrate()` upgrades old files. */
  schemaVersion: number;
  id: UUID;
  meta: ProjectMeta;
  projection: ProjectionSettings;
  view: SavedView;
  /**
   * The area of the world this map is about, as WGS84 [w, s, e, n] — or null
   * for "everywhere", which is the default.
   *
   * A map of the Americas has no use for Asian coastlines or seven thousand
   * European cities: they cost time to project and draw, they widen the view so
   * far that the subject is a thumbnail, and they are visual noise in every
   * export. Setting this crops the reference geography, and stops the view
   * panning or zooming out past the region — the map behaves like a sheet of
   * paper of a definite size rather than a window onto the whole globe.
   *
   * It bounds nothing about the *document*: territories, labels and settlements
   * outside it are still drawn, still exported and still editable. This is a
   * statement about what the reference data is for, not a fence around your work.
   */
  workingExtent: [number, number, number, number] | null;
  layers: Record<UUID, MapLayer>;
  territories: Record<UUID, Territory>;
  settlements: Record<UUID, Settlement>;
  linearFeatures: Record<UUID, LinearFeature>;
  labels: Record<UUID, MapLabel>;
  styles: StyleSheet;
  timeline: TimelineSettings;
  basemap: BasemapLayerState[];
  /** Colour applied behind everything — the ocean (§17). */
  oceanColor: Color;
  landColor: Color;
  legend: LegendSettings;
  compass: CompassSettings;
}

/** Where a piece of map furniture sits inside the frame. */
export type FurniturePosition = 'top-left' | 'top-right' | 'bottom-left' | 'bottom-right';

/**
 * One row of the legend (§26).
 *
 * A row names a style class rather than carrying its own appearance, so the
 * swatch is drawn by the same code that draws the map. Change the Sovereign
 * Border style and the legend's rule changes with it — which is the only way a
 * legend stays true as a map is restyled.
 */
export interface LegendEntry {
  id: UUID;
  /** Which part of the stylesheet `styleId` refers to, and how to draw it. */
  kind: 'symbol' | 'line' | 'fill';
  styleId: UUID;
  text: string;
  hidden: boolean;
}

export interface LegendSettings {
  enabled: boolean;
  title: string;
  position: FurniturePosition;
  /**
   * Rebuild the rows from what the map actually contains whenever it is drawn.
   * Editing a row turns this off, because the user's arrangement is then the
   * thing to preserve.
   */
  auto: boolean;
  entries: LegendEntry[];
}

export interface CompassSettings {
  enabled: boolean;
  style: 'star' | 'rose' | 'arrow';
  position: FurniturePosition;
  /** Diameter in output px, before the export's style scale. */
  size: number;
}

/** Collections that hold identified features; used by the undo system. */
export type FeatureCollectionKey = 'territories' | 'settlements' | 'linearFeatures' | 'labels';

/** The union of everything a `FeatureCollectionKey` can address. */
export type AnyFeature = Territory | Settlement | LinearFeature | MapLabel;

/** Handy alias for turf round-trips. */
export type GeoFeature<G extends Polygon | MultiPolygon | Point | LineString | MultiLineString> =
  Feature<G, Record<string, unknown>>;
