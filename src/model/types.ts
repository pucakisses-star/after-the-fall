/**
 * What kind of content a layer holds. A layer only ever holds one kind, which is
 * what lets the renderer build one OpenLayers layer per map layer and keeps
 * z-ordering meaningful.
 */
export type LayerKind =
  | 'group'
  | 'ocean'
  | 'basemap'
  | 'territory'
  | 'border'
  | 'river'
  | 'road'
  | 'settlement'
  | 'label'
  | 'graticule'
  | 'reference-image';

export interface MapLayer {
  id: UUID;
  name: string;
  kind: LayerKind;
  /** `null` for top-level layers. Groups nest arbitrarily deep. */
  parentId: UUID | null;
  visible: boolean;
  locked: boolean;
  opacity: number;
  /** Collapsed state of a group in the layer tree. UI-ish, but worth persisting. */
  collapsed: boolean;
  /** Order among siblings, ascending = drawn first = underneath. */
  order: number;
}

