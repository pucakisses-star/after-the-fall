/** Fields shared by every addressable thing on the map. */
export interface FeatureBase {
  id: UUID;
  layerId: UUID;
  name: string;
  notes: string;
  locked: boolean;
  hidden: boolean;
  timeline: TimelineRange;
}

export interface Territory extends FeatureBase {
  shortName: string;
  politicalType: PoliticalType;
  /**
   * Hierarchy (§7). Points at another Territory. An Empire has `parentId: null`;
   * its Kingdoms point at it; their Duchies point at the Kingdoms, and so on.
   * There is no depth limit — `depthOf()` in `src/model/hierarchy.ts` walks it.
   */
  parentId: UUID | null;
  /** Overlord for personal unions / vassalage that does not match the containment tree. */
  liegeId: UUID | null;
  /** Settlement id of the capital. */
  capitalId: UUID | null;
  geometry: Polygon | MultiPolygon;
  styleClassId: UUID;
  /** Sparse overrides on top of the style class (§40: "objects may override"). */
  styleOverrides: Partial<TerritoryStyle>;
  /**
   * When true the territory takes its fill from its parent, lightened by
   * `shadeStep` per level of depth (§7, §9).
   */
  inheritParentColor: boolean;
  /** Which border weight to draw around this territory (§8). */
  borderKind: BorderStyleKind;
  labelId: UUID | null;
}

export type BorderStyleKind =
  | 'international'
  | 'major-political'
  | 'subordinate'
  | 'provincial'
  | 'county'
  | 'disputed'
  | 'ceasefire'
  | 'historical'
  | (string & {});

