/**
 * Central data model.
 *
 * Architectural rule (spec §60): three things are kept strictly separate.
 *
 *   1. GEOGRAPHIC DATA  — geometry + semantic attributes. Lives in this file.
 *                         Always WGS84 (EPSG:4326) lon/lat. Never projected on disk.
 *   2. CARTOGRAPHIC APPEARANCE — style classes in `StyleSheet`. Features reference a
 *                         style class by id and may carry a sparse override object.
 *   3. UI STATE         — current tool, selection, hover, zoom. Lives in `src/state/uiStore.ts`
 *                         and is deliberately NOT part of `MapProject`, so it is never
 *                         serialised into a project file.
 *
 * Everything here must stay JSON-serialisable: no Dates, no Maps, no class instances,
 * no functions. That is what makes autosave, undo patches and the .atfmap file format work.
 */

import type { Feature, MultiPolygon, Point, Polygon, LineString, MultiLineString } from 'geojson';

/** Stable identifier. Generated by `newId()` in `./ids`. */
export type UUID = string;

/** Hex colour, `#rrggbb` or `#rrggbbaa`. */
export type Color = string;

// ---------------------------------------------------------------------------
// Timeline (spec §30 — designed in now, driven by UI in Phase 4)
// ---------------------------------------------------------------------------

/**
 * Half-open year range: a feature exists when `start <= year < end`.
 * `null` means unbounded in that direction. Years are astronomical
 * (i.e. 0 is 1 BC, -1 is 2 BC), so ordinary numeric comparison works.
 */
export interface TimelineRange {
  start: number | null;
  end: number | null;
}

export interface TimelineSettings {
  enabled: boolean;
  currentYear: number;
  minYear: number;
  maxYear: number;
  /** Step of the timeline slider, in years. */
  step: number;
}

// ---------------------------------------------------------------------------
// Projections (spec §4)
// ---------------------------------------------------------------------------

export type ProjectionId =
  | 'EPSG:3857' // Web Mercator
  | 'EPSG:4326' // Equirectangular / plate carrée
  | 'ATF:ROBINSON'
  | 'ATF:WINKEL3'
  | 'ATF:NATURALEARTH'
  | 'ATF:LCC'
  | 'ATF:ALBERS'
  | 'ATF:ORTHOGRAPHIC'
  | 'ATF:MERCATOR'
  | (string & {}); // custom proj4 definitions get an arbitrary id

export interface ProjectionSettings {
  id: ProjectionId;
  /** Human-readable name shown in the status bar and project dialog. */
  name: string;
  /** proj4 definition string. Empty for the two EPSG codes OpenLayers ships with. */
  proj4: string;
  /** Extent in projected units, used to seed the OpenLayers view. */
  extent: [number, number, number, number] | null;
  /** `m` (metres) or `degrees`. Drives the scale bar and the coordinate readout. */
  units: 'm' | 'degrees';
}

// ---------------------------------------------------------------------------
// Styling (spec §8, §9, §40, §42, §45)
// ---------------------------------------------------------------------------

export type HatchKind =
  | 'none'
  | 'diagonal'
  | 'reverse-diagonal'
  | 'crosshatch'
  | 'dots'
  | 'vertical'
  | 'horizontal';

/**
 * A hatch fill. Rendered to a CanvasPattern for the live map and to an SVG
 * `<pattern>` on export, from this one definition — see `src/render/patterns.ts`.
 */
export interface HatchPattern {
  kind: HatchKind;
  /** Degrees, clockwise. Applied on top of the base angle implied by `kind`. */
  angle: number;
  /** Distance between strokes, in CSS px at 1:1 zoom. */
  spacing: number;
  thickness: number;
  color: Color;
  opacity: number;
}

export type DashKind = 'solid' | 'dashed' | 'dotted' | 'dash-dot' | 'double' | 'alternating';

export interface LineStyle {
  color: Color;
  width: number;
  opacity: number;
  dash: DashKind;
  /** Second stroke drawn underneath, used for `double` and casing effects. */
  casingColor: Color | null;
  casingWidth: number;
  lineCap: 'butt' | 'round' | 'square';
  lineJoin: 'miter' | 'round' | 'bevel';
}

export interface TerritoryStyle {
  fillColor: Color;
  fillOpacity: number;
  pattern: HatchPattern | null;
  /** Outline drawn around the territory itself. Border *hierarchy* (§8) is a
   *  separate concern handled by `BorderStyleKind` on derived border geometry. */
  outline: LineStyle;
}

export interface TextStyle {
  fontFamily: string;
  fontSize: number;
  fontWeight: number;
  italic: boolean;
  color: Color;
  opacity: number;
  /** Letter spacing in px. Country and ocean labels use extreme values (§42, §43). */
  tracking: number;
  /** Multiplier on font size. */
  lineHeight: number;
  transform: 'none' | 'uppercase' | 'lowercase' | 'capitalize';
  haloColor: Color | null;
  haloWidth: number;
  /** Stroke drawn on the glyph outline itself, distinct from the halo. */
  outlineColor: Color | null;
  outlineWidth: number;
  align: 'left' | 'center' | 'right';
}

export type SymbolShape =
  | 'circle'
  | 'filled-circle'
  | 'double-circle'
  | 'star'
  | 'square'
  | 'filled-square'
  | 'diamond'
  | 'triangle'
  | 'cross'
  | 'castle'
  | 'anchor'
  | 'custom-svg';

export interface SymbolStyle {
  shape: SymbolShape;
  size: number;
  fillColor: Color;
  strokeColor: Color;
  strokeWidth: number;
  opacity: number;
  /** Raw SVG path data, used when `shape === 'custom-svg'`. Drawn in a 0..100 box. */
  customPath: string | null;
}

/** A named, reusable style (spec §40). Editing one updates every feature that uses it. */
export interface StyleClass<T> {
  id: UUID;
  name: string;
  /** Style classes cannot be deleted while built-in, to keep projects loadable. */
  builtin: boolean;
  style: T;
}

export interface StyleSheet {
  territory: Record<UUID, StyleClass<TerritoryStyle>>;
  line: Record<UUID, StyleClass<LineStyle>>;
  text: Record<UUID, StyleClass<TextStyle>>;
  symbol: Record<UUID, StyleClass<SymbolStyle>>;
}

